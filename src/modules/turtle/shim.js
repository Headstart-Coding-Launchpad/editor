// How many lines buildTurtleProgram puts before the student's code: the worker's line numbers
// (errors, the name-tag panel's #@peek line, a step recorder) are this much higher than the
// editor's.
export const TURTLE_LINE_OFFSET = 2

/**
 * The program the worker runs: the shim on line 1, then (course mode, `course` from course.js
 * courseRunSpec) the map set-up on line 2, which is otherwise blank, so the student's code always
 * starts on line TURTLE_LINE_OFFSET + 1.
 */
export function buildTurtleProgram(code, { course = null } = {}) {
  const setup = course ? `_turtle_course_setup(${JSON.stringify(JSON.stringify(course))})` : ''
  return [`exec(${JSON.stringify(TURTLE_SHIM)}, globals())`, setup, code].join('\n')
}

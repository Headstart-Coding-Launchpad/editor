// Python-side `turtle` module shim, prepended to student code (same technique as
// electronics' MICROPYTHON_SHIM in ../electronics/index.js): a plain array of
// Python source lines, joined and exec'd via `exec(<json>, globals())` before the
// student's own code runs. Backed by JS bridge functions on the shared Pyodide
// worker's globalThis (see ../python/pyodide.worker.js), following the same
// `import js as _js` pattern the existing GPIO shim uses.
//
// Phase 1 command surface: forward/fd, backward/bk, left/lt, right/rt,
// penup/pu, pendown/pd, pencolor, goto/setpos, setheading/seth, home,
// reset/clear, position/pos, heading, isdown. Single default turtle only —
// no Turtle() instances.
//
// pensize/width (read back with no argument), dot and speed (P6-10): speed() is recorded so
// a Run plays the drawing at that pace (./playback.js), and circle()'s own small turns are
// instant, as in real turtle.
//
// Phase 2 adds: circle (built as forward/left steps — see _mark_command),
// begin_fill/end_fill/fillcolor/color, stamp, write, bgcolor, colormode.
// colormode is handled entirely here via _format_color — the JS bridge and
// engine.js only ever see final CSS-compatible color strings.
//
// hideturtle/ht, showturtle/st and isvisible toggle state.visible, which controls
// whether the 🐢 marker is drawn (see ../turtle/draw.js drawTurtleMarker).
//
// Course mode (P6-11, ./course.js): buildTurtleProgram's line 2 sets up the map; forward() and
// backward() then default to one square on a grid, left()/right() to 90 degrees, and the sensors
// wall_ahead/wall_left/wall_right/at_goal/on_pickup/collected answer from the map. Bridge calls
// that return 'error|…' raise ValueError and 'stop|…' raises _CourseStop (the run ends there).
//
// `done`/`mainloop`/`bye` and a no-op `Screen()` are included as harmless stubs
// since they're near-universal turtle boilerplate that would otherwise crash a
// script for no visual reason in this headless model.
